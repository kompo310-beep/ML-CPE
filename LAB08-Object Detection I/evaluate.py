import argparse
import json
import shutil
from pathlib import Path

from ultralytics import YOLO


ROOT = Path(__file__).resolve().parent
DEFAULT_MODEL = ROOT / "runs" / "yolo11s" / "weights" / "best.pt"
DEFAULT_DATA = ROOT / "dataset" / "data.yaml"
OUTPUT_ROOT = ROOT / "outputs"


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate the trained YOLO11s model."
    )
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=4)
    args = parser.parse_args()

    if not args.model.is_file():
        raise FileNotFoundError(
            f"Model not found: {args.model}. Run train.py first."
        )

    if not args.data.is_file():
        raise FileNotFoundError(
            f"Dataset config not found: {args.data}. Run prepare_dataset.py first."
        )

    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    training_history_dir = OUTPUT_ROOT / "training_history"
    training_history_dir.mkdir(parents=True, exist_ok=True)

    # Delete the graph generated by the previous evaluation script, if present.
    old_graph = training_history_dir / "training_curves.png"
    if old_graph.is_file():
        old_graph.unlink()
        print(f"Deleted old graph: {old_graph}")

    # Copy training history files next to the evaluation outputs.
    training_run_dir = args.model.resolve().parent.parent
    for filename in ("results.csv", "results.png", "args.yaml"):
        source = training_run_dir / filename
        if source.is_file():
            shutil.copy2(source, training_history_dir / filename)

    model = YOLO(str(args.model))

    print("Evaluating the model on the validation split...")
    metrics = model.val(
        data=str(args.data.resolve()),
        split="val",
        imgsz=args.imgsz,
        batch=args.batch,
        device="cpu",
        workers=0,
        plots=True,
        project=str(OUTPUT_ROOT / "evaluation"),
        name="validation",
        exist_ok=True,
    )

    result_dir = Path(metrics.save_dir)
    summary = {
        key: float(value)
        for key, value in metrics.results_dict.items()
    }

    metrics_file = result_dir / "metrics.json"
    metrics_file.write_text(
        json.dumps(summary, indent=2),
        encoding="utf-8",
    )

    print("\nValidation results:")
    for name, value in summary.items():
        print(f"{name}: {value:.4f}")

    print(f"\nTraining history: {training_history_dir}")
    print(f"Evaluation metrics: {metrics_file}")
    print(f"Evaluation plots: {result_dir}")


if __name__ == "__main__":
    main()